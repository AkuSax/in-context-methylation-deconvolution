MISSING_PROBS = (0.45, 0.35, 0.15, 0.05)
MARKER_MODE_PROBS = {"pick": 0.6, "contrast": 0.2, "informative": 0.1, "random": 0.1}
VALIDATION_MARKER_MODE = "pick"
SHARPEN = (1.3, 2.2)
POOL_MIN_RANGE = 0.3
# v3 reference-to-bulk technical shift (simulator.simulate_task, tech_shift=True),
# with v5 per-CpG M-value offsets on a random subset of CpGs.
TECH_SHIFT_RANGES = dict(tech_global=(0.0, 0.04), tech_batch=(0.0, 0.04),
                         tech_warp_scale=(0.9, 1.1), tech_warp_shift_sd=0.1,
                         tech_cpg_m_sd=(0.0, 0.5), tech_cpg_m_frac=(0.2, 1.0), tech_cpg_m_df=30.0)
TRAIN_NOISE = (0.005, 0.06)
# v6 sources: (panel name, simulate_cohort arguments, sharpen rule, probability).
# Sharpen rule: "all" stretches every profile (v4), "half" stretches GSE35069 donors in
# half of the cohorts, None leaves the measured profiles alone.
SOURCES = (
    ("gse35069", dict(), "all", 0.25),
    ("joint", dict(mixture_group="GSE103541"), None, 0.25),
    ("joint", dict(mixture_group="GSE103541", cross_study=True), "half", 0.25),
    ("joint", dict(mixture_group="GSE35069", cross_study=True), "half", 0.25),
)
VALIDATION_SOURCES = (
    ("joint", dict(mixture_group="GSE103541"), None),
    ("joint", dict(mixture_group="GSE103541", cross_study=True), None),
    ("joint", dict(mixture_group="GSE35069", cross_study=True), None),
)
COHORT_SIZES = {1: 0.1, 4: 0.2, 8: 0.4, 16: 0.3}
VALIDATION_COHORT = 8


def sharpen_args(rule, rng):
    if rule == "all":
        return dict(sharpen=SHARPEN)
    if rule == "half" and rng.random() < 0.5:
        return dict(sharpen=SHARPEN, sharpen_groups=("GSE35069",))
    return {}

# Fixed synthetic validation regimes: (name, n_types, missing, donor_mismatch).
VALIDATION_REGIMES = (
    ("clean12", 12, 0, False),
    ("mismatch12", 12, 0, True),
    ("missing1_12", 12, 1, False),
    ("missing1_mismatch12", 12, 1, True),
    ("missing2_mismatch12", 12, 2, True),
    ("mismatch6", 6, 0, True),
    ("missing1_mismatch6", 6, 1, True),
)
DETECTION_PAIRS = (
    ("clean12", "missing1_12"),
    ("mismatch12", "missing1_mismatch12"),
    ("mismatch6", "missing1_mismatch6"),
)


def collate(cohorts):
    """One batch from a list of cohorts (each a list of tasks with one reference)."""
    tasks = [t for cohort in cohorts for t in cohort]
    ids = np.repeat(np.arange(len(cohorts)), [len(c) for c in cohorts])
    reference = np.stack([t.reference_mean for t in tasks])
    sd = np.stack([t.reference_sd for t in tasks])
    bulk = np.stack([t.bulk for t in tasks])
    truth = np.stack([t.fractions for t in tasks])
    fit = rpc_fit(reference, bulk)
    as_t = lambda x: torch.as_tensor(x, dtype=torch.float32)  # noqa: E731
    return dict(reference=as_t(reference), sd=as_t(sd), bulk=as_t(bulk), truth=as_t(truth),
                cohort=torch.as_tensor(ids), fit=fit)


def fit_slice(fit: RPCFit, index) -> RPCFit:
    return RPCFit(*(getattr(fit, name)[index] for name in RPCFit.__dataclass_fields__))


def to_device(batch, device):
    """Move a batch to the model device; RPC fit fields become float32 there."""
    fit = RPCFit(*(getattr(batch["fit"], n).to(device, torch.float32 if getattr(batch["fit"], n).is_floating_point() else None)
                   for n in RPCFit.__dataclass_fields__))
    return dict({k: v.to(device) for k, v in batch.items() if k != "fit"}, fit=fit)


class PriorTasks(IterableDataset):
    """Endless batches from the training prior. Each batch shares K and M."""

    def __init__(self, panels, pools, seed, batch_size, types, markers):
        self.panels, self.pools, self.seed, self.batch_size = panels, pools, seed, batch_size
        self.types, self.markers = types, markers

    def __iter__(self):
        info = get_worker_info()
        worker = 0 if info is None else info.id
        torch.set_num_threads(1)
        rng = np.random.default_rng([self.seed, worker])
        modes, mode_p = list(MARKER_MODE_PROBS), list(MARKER_MODE_PROBS.values())
        sizes, size_p = list(COHORT_SIZES), list(COHORT_SIZES.values())
        source_p = [s[3] for s in SOURCES]
        while True:
            k = int(rng.integers(self.types[0], self.types[1] + 1))
            m = int(rng.integers(self.markers[0], self.markers[1] + 1))
            size = int(rng.choice(sizes, p=size_p))
            cohorts = []
            for _ in range(max(1, self.batch_size // size)):
                name, extra, rule, _ = SOURCES[int(rng.choice(len(SOURCES), p=source_p))]
                missing = int(rng.choice(4, p=MISSING_PROBS))
                cohorts.append(simulator.simulate_cohort(
                    self.panels[name], rng, size, n_markers=m, n_types=k, missing=missing, augment=True,
                    donor_mismatch=bool(rng.random() < 0.5), noise=float(rng.uniform(*TRAIN_NOISE)),
                    marker_mode=str(rng.choice(modes, p=mode_p)), zero_type_prob=0.1,
                    concentration_range=(2, 30), neutrophil_weight=float(rng.uniform(1, 6)),
                    tech_shift=True, **TECH_SHIFT_RANGES,
                    candidate_pool=self.pools[name], **extra, **sharpen_args(rule, rng),
                ))
            yield collate(cohorts)


def validation_set(panels, pools, seed, per_regime, markers):
    """Cohorts of VALIDATION_COHORT samples from held-out donors, cycling VALIDATION_SOURCES."""
    rng = np.random.default_rng([seed, 999])
    out = {}
    for name, k, missing, mismatch in VALIDATION_REGIMES:
        cohorts = []
        for i in range(max(1, per_regime // VALIDATION_COHORT)):
            panel, extra, rule = VALIDATION_SOURCES[i % len(VALIDATION_SOURCES)]
            cohorts.append(simulator.simulate_cohort(
                panels[panel], rng, VALIDATION_COHORT, n_markers=markers, n_types=k, missing=missing,
                donor_mismatch=mismatch, augment=True, marker_mode=VALIDATION_MARKER_MODE,
                tech_shift=True, **TECH_SHIFT_RANGES, candidate_pool=pools[panel], **extra,
                **sharpen_args(rule, rng)))
        out[name] = collate(cohorts)
    return out


def predict(model, batch, chunk=32):
    """Predictions in chunks that never split a cohort (cohort rows are contiguous)."""
    means, lows, highs, has_other, nll = [], [], [], [], []
    device = next(model.parameters()).device
    batch = to_device(batch, device)
    n = len(batch["truth"])
    ids = batch["cohort"]
    starts = [0] + (1 + torch.nonzero(ids[1:] != ids[:-1]).flatten()).tolist() + [n]
    cuts = [0]
    for edge in starts[1:]:
        if edge - cuts[-1] >= chunk or edge == n:
            cuts.append(edge)
    with torch.inference_mode():
        for s, e in zip(cuts[:-1], cuts[1:]):
            idx = slice(s, e)
            p = model(batch["reference"][idx], batch["sd"][idx], batch["bulk"][idx], fit_slice(batch["fit"], idx),
                      ids[idx])
            means.append(p.mean)
            q = p.sample(400).quantile(torch.tensor([0.05, 0.95], device=device), dim=0)
            lows.append(q[0]); highs.append(q[1])
            has_other.append(p.has_other.probs)
            nll.append(-p.log_prob(batch["truth"][idx]))
    cat = lambda xs: torch.cat(xs).cpu().numpy().astype(float)  # noqa: E731
    return cat(means), cat(lows), cat(highs), cat(has_other), cat(nll)


def auroc(negative, positive):
    """Probability a positive scores above a negative (ties count half)."""
    neg, pos = np.asarray(negative, float), np.asarray(positive, float)
    greater = (pos[:, None] > neg[None, :]).mean()
    ties = (pos[:, None] == neg[None, :]).mean()
    return float(greater + 0.5 * ties)


def score(model, validation, prior_other):
    model.eval()
    rows, detectors = [], {}
    for name, batch in validation.items():
        truth = batch["truth"].numpy().astype(float)
        ref = batch["reference"].numpy().astype(float)
        bulk = batch["bulk"].numpy().astype(float)
        fit = batch["fit"]
        rpc = fit.fractions.numpy()
        raw_sum = fit.coefficients.clamp_min(0).sum(-1).numpy()
        raw_other = np.clip(1 - raw_sum, 0, 1)
        nnls = np.stack([solvers.nnls(r, b[:, None])[0] for r, b in zip(ref, bulk)])
        cp = np.stack([solvers.cp_inequality(r, b[:, None])[0] for r, b in zip(ref, bulk)])
        mean, low, high, p_other, nll = predict(model, batch)
        n = len(truth)
        methods = {
            "model": (mean[:, :-1], mean[:, -1]),
            "RPC": (rpc, np.zeros(n)),
            "RPC_shrunk_const": (rpc * (1 - prior_other), np.full(n, prior_other)),
            "RPC_rawsum": (rpc * (1 - raw_other)[:, None], raw_other),
            "NNLS": (nnls, np.clip(1 - nnls.sum(1), 0, 1)),
            "CP_ineq": (cp, np.clip(1 - cp.sum(1), 0, 1)),
        }
        detectors[name] = {
            "model_other": mean[:, -1], "model_p_other": p_other,
            "RPC_rawsum": raw_other, "NNLS": methods["NNLS"][1], "CP_ineq": methods["CP_ineq"][1],
        }
        abundant = truth[:, -1] >= 0.05
        for method, (kept, other) in methods.items():
            e_kept = kept - truth[:, :-1]
            e_other = other - truth[:, -1]
            row = dict(
                regime=name, method=method, n_tasks=n, n_types=truth.shape[1] - 1,
                kept_rmse_pts=100 * float(np.sqrt(np.mean(e_kept ** 2))),
                other_mae_pts=100 * float(np.mean(np.abs(e_other))),
                other_bias_pts=100 * float(np.mean(e_other)),
                mean_true_other_pts=100 * float(truth[:, -1].mean()),
            )
            if abundant.any():
                row["n_abundant_other"] = int(abundant.sum())
                row["other_mae_abundant_pts"] = 100 * float(np.mean(np.abs(e_other[abundant])))
                row["kept_rmse_abundant_pts"] = 100 * float(np.sqrt(np.mean(e_kept[abundant] ** 2)))
            if method == "model":
                covered = (truth >= low) & (truth <= high)
                row.update(
                    nll=float(nll.mean()),
                    marginal_90_coverage=float(covered.mean()),
                    joint_coverage_of_marginal_90_intervals=float(covered.all(axis=1).mean()),
                    mean_90_width_pts=100 * float((high - low).mean()),
                    mean_p_other=float(p_other.mean()),
                    sd_pred_other_pts=100 * float(mean[:, -1].std()),
                )
            rows.append(row)
    detection = []
    for clean, missing in DETECTION_PAIRS:
        for det in detectors[clean]:
            detection.append(dict(negative=clean, positive=missing, detector=det,
                                  auroc=auroc(detectors[clean][det], detectors[missing][det])))
    model.train()
    return rows, detection


def lr_at(step, steps, warmup, base):
    if step < warmup:
        return base * (step + 1) / warmup
    progress = (step - warmup) / max(1, steps - warmup)
    return base * (0.1 + 0.9 * 0.5 * (1 + math.cos(math.pi * progress)))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--steps", type=int, default=3000)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--lr", type=float, default=5e-4)
    parser.add_argument("--warmup", type=int, default=200)
    parser.add_argument("--width", type=int, default=64)
    parser.add_argument("--heads", type=int, default=4)
    parser.add_argument("--blocks", type=int, default=3)
    parser.add_argument("--types", type=int, nargs=2, default=(4, 12))
    parser.add_argument("--markers", type=int, nargs=2, default=(150, 600))
    parser.add_argument("--val-markers", type=int, default=300)
    parser.add_argument("--val-per-regime", type=int, default=64)
    parser.add_argument("--eval-every", type=int, default=500)
    parser.add_argument("--workers", type=int, default=6)
    parser.add_argument("--threads", type=int, default=8)
    parser.add_argument("--device", default="cpu", help="cpu or cuda")
    parser.add_argument("--panels", type=Path, default=None,
                        help="v6 panel file from simulator.save_panels; built from the raw data if omitted")
    parser.add_argument("--no-cohort", action="store_true", help="ablation: v5 architecture, no cohort features")
    args = parser.parse_args()
    if args.out.exists():
        parser.error("--out must be a new directory")
    if not 2 <= args.types[0] <= args.types[1] <= 12 or args.markers[0] <= args.types[1]:
        parser.error("Use 2 to 12 types and more markers than types")
    args.out.mkdir(parents=True)

    torch.set_num_threads(args.threads)
    torch.manual_seed(args.seed)
    # Panels and pools: the pools are screened on training donors only (build_v6_panels).
    bundle = (simulator.load_panels(args.panels) if args.panels
              else simulator.build_v6_panels(seed=args.seed, min_range=POOL_MIN_RANGE))
    train_panels, validation_panels, pools = bundle["train"], bundle["validation"], bundle["pools"]
    for p in (*train_panels.values(), *validation_panels.values()):
        p.cube()
    validation = validation_set(validation_panels, pools, args.seed, args.val_per_regime, args.val_markers)
    loader = DataLoader(PriorTasks(train_panels, pools, args.seed, args.batch_size, args.types, args.markers),
                        batch_size=None, num_workers=args.workers, persistent_workers=args.workers > 0,
                        prefetch_factor=4 if args.workers else None)
    device = torch.device(args.device)
    model = Deconvolver(width=args.width, heads=args.heads, blocks=args.blocks, cohort=not args.no_cohort).to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=1e-4)

    log, evals = [], []
    other_sum, other_count, best = 0.0, 0, math.inf
    start = time.time()
    for step, batch in enumerate(loader):
        if step >= args.steps:
            break
        for group in optimizer.param_groups:
            group["lr"] = lr_at(step, args.steps, args.warmup, args.lr)
        batch = to_device(batch, device)
        loss = -model(batch["reference"], batch["sd"], batch["bulk"], batch["fit"],
                      batch["cohort"]).log_prob(batch["truth"]).mean()
        if not torch.isfinite(loss):
            raise ValueError(f"Training loss is not finite at step {step}")
        optimizer.zero_grad()
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        optimizer.step()
        other_sum += float(batch["truth"][:, -1].sum()); other_count += len(batch["truth"])
        if (step + 1) % 100 == 0:
            print(f"step {step + 1} loss {np.mean([x['loss'] for x in log[-99:]] + [float(loss)]):.2f} {time.time() - start:.0f}s", flush=True)
        log.append(dict(step=step, loss=float(loss), types=batch["truth"].shape[1] - 1,
                        markers=batch["bulk"].shape[1], seconds=time.time() - start))
        if (step + 1) % args.eval_every == 0 or step + 1 == args.steps:
            prior_other = other_sum / other_count
            rows, detection = score(model, validation, prior_other)
            val_nll = float(np.mean([r["nll"] for r in rows if r["method"] == "model"]))
            evals.append(dict(step=step + 1, val_nll=val_nll, seconds=time.time() - start))
            summary = {r["regime"]: round(r["kept_rmse_pts"], 2) for r in rows if r["method"] == "model"}
            print(f"step {step + 1} loss {np.mean([x['loss'] for x in log[-args.eval_every:]]):.2f} "
                  f"val_nll {val_nll:.2f} kept_rmse {summary} {time.time() - start:.0f}s", flush=True)
            if val_nll < best:
                best = val_nll
                torch.save(model.state_dict(), args.out / "model.pt")
                best_result = dict(step=step + 1, prior_mean_other=prior_other, scores=rows, detection=detection)
    model.load_state_dict(torch.load(args.out / "model.pt", map_location=device))
    settings = {key: (str(value) if isinstance(value, Path) else value) for key, value in vars(args).items() if key != "out"}
    settings["cohort"] = not args.no_cohort
    result = dict(
        version="v6", settings=settings,
        source={name: p.source for name, p in train_panels.items()},
        preprocessing={name: p.preprocessing for name, p in train_panels.items()},
        train_donors=sorted(set().union(*(p.donors.unique() for p in train_panels.values()))),
        validation_donors=sorted(set().union(*(p.donors.unique() for p in validation_panels.values()))),
        training_prior=dict(missing_probs=MISSING_PROBS, marker_modes=MARKER_MODE_PROBS,
                            donor_mismatch=0.5, noise=TRAIN_NOISE, zero_type_prob=0.1,
                            concentration=(2, 30), neutrophil_weight=(1, 6), synthetic="sparse",
                            markers=tuple(args.markers), tech_shift=True, **TECH_SHIFT_RANGES,
                            sharpen=SHARPEN, pool_min_range=POOL_MIN_RANGE,
                            pool_size={name: int(len(rows)) for name, rows in pools.items()},
                            pool_source="training donors",
                            sources=[dict(panel=a, args=b, sharpen=c, prob=d) for a, b, c, d in SOURCES],
                            cohort_sizes=COHORT_SIZES, tight_prob=0.5, tight_concentration=(20.0, 500.0),
                            sample_shift=simulator.SAMPLE_SHIFT),
        validation_prior=dict(tech_shift=True, noise=0.02, markers=args.val_markers,
                              marker_mode=VALIDATION_MARKER_MODE, cohort_size=VALIDATION_COHORT,
                              sources=[dict(panel=a, args=b, sharpen=c) for a, b, c in VALIDATION_SOURCES],
                              pool="training-donor screen", **TECH_SHIFT_RANGES),
        best=best_result, evaluations=evals,
    )
