"""Train and score the reference-conditioned model on simulated tasks.

v2 (2026-11-11):
- Fresh simulated tasks every step from donor-held-out GSE35069 partitions,
  generated by worker processes. v1 reused 288 fixed tasks for 12 epochs.
- RPC comes from `rpc_torch` (matches EpiDISH to ~1e-15), so no R per batch.
- Training prior: 4–12 retained types and 80–250 markers per batch; 0–3
  missing types (about half of tasks have one or more); donor mismatch in half;
  sparse synthetic subtypes; mostly contrast markers; an over-complete type in
  10%; measurement noise 0.5–4%.
- Scorecard adds the baselines a constant `other` guess must beat (RPC shrunk
  by the training-prior mean of `other`, and that constant as the `other`
  estimate), RPC's raw slope sum as a classical missing-mass diagnostic, and
  clean-versus-missing detection AUROC.

v3 (2026-11-11): one causal change plus a marker-range change, so the effect
can be attributed.
- Reference-to-bulk technical shift on the bulk only (`simulator.simulate_task`
  with `tech_shift=True`): global offset, per-CpG batch offsets and an M-value
  warp. Real GSE110554 mixtures differ from their reference by an intercept of
  about 0.028 and a residual scale of about 0.038, which v2's simulator never
  produced, so v2 read that technical noise as missing mass.
- Measurement noise drawn from 0.5–6% (v2: 0.5–4%).
- Training markers 150–600 (v2: 80–250); validation markers 300 (v2: 150).
- Validation regimes unchanged, with the shift on.

v4 (2026-11-11): realistic marker panels. GSE35069 profiles are compressed at
marker CpGs (median between-type range 0.75 vs 0.88 on EPIC Noob at the same
CpGs; 6x fewer CpGs with range >= 0.8), so simulated panels were far weaker than
real `pick_markers` panels, and on real panels v2/v3 read ordinary noise as
missing mass.
- Candidate CpGs come from `simulator.screen_pool(train_panel, 0.3)`: cell-type
  mean range >= 0.3 on TRAINING donors only, reused for validation.
- Every profile is stretched in M-value space by a ~ U(1.3, 2.2) (`sharpen`).
- New `pick` marker mode mirrors `reference.pick_markers` (significance filter,
  then rank by difference); training mix pick 0.6 / contrast 0.2 / informative
  0.1 / random 0.1; validation uses pick.
- Per-CpG batch SD up to 0.06 (v3: 0.04).
Matched check (286 markers, 6 types): median range 0.89–0.92 vs real 0.88, and
RPC clean RMSE 1.8–2.0 vs real 1.72 (v3 simulator: 0.58 and 2.9).

v5 (2026-11-11): realistic residual shape. On GSE110554 the v4 reference
matched, but real sorted-vs-mixture residuals carry many moderate per-CpG
outliers (standardised RPC residuals P(|z|>2) 0.104, P(|z|>3) 0.038 vs v4
simulator 0.069 / 0.017, Gaussian 0.045 / 0.003), concentrated at mid-range
beta and recurring at the same CpGs; v4 read them as missing mass.
- Per-CpG M-value offsets d_j = s * t_30 on a fraction ~ U(0.2, 1.0) of CpGs,
  s ~ U(0, 0.5), inside the bulk-only technical shift.
- Per-CpG beta-scale batch SD back to at most 0.04 (v4: 0.06), which inflated
  the residual scale without producing outliers.
Matched check (286 markers, 6 types, batch 0.02–0.03, frac 0.3–0.5, s 0.3):
P(|z|>2) 0.09–0.12, P(|z|>3) 0.03–0.05, P(|z|>5) 0.004–0.008, kurtosis 6–9,
robust scale 0.032–0.045, vs real 0.104 / 0.038 / 0.004 / 7.4 / 0.039.
The false `other` on real mixtures comes from a per-CpG offset shared by all
12 mixtures (SD 0.043; M-scale SD about 0.24 natural-log units on all CpGs),
not from biology: it is uncorrelated with every type profile and lies outside
the reference span. Reproduction check, gpu_v4 on simulated clean 6-type
tasks: `other` 6.7 at the matched point, 11.8 with s = 0.35 on all CpGs (real
GSE110554: 18.9). The prior therefore reaches s = 0.5 on up to all CpGs.

v6 (2026-11-12): measured cross-study offsets and cohort input. v5's `other`
did not transfer: 8-19 points on four whole-blood cohorts, and its hand-built
offset is the same for every cell type while the measured GSE103541-vs-GSE35069
offset is half type-specific. A cohort-median residual carries the batch offset
(results/cohort_center_gpu_v5) but must not be subtracted.
- Sources (`simulator.build_v6_panels`): GSE35069 alone as in v5 (seven types,
  sharpened), GSE103541 alone (27 donors, five types, not sharpened), and
  cross-study tasks in both directions on the five common types, where the
  reference comes from one study and the mixture from the other. Equal weight.
  In cross-study tasks GSE35069 is sharpened half the time.
- Every batch is a set of cohorts (`simulator.simulate_cohort`): 1, 4, 8 or 16
  samples that share reference, markers, missing types and technical shift.
  Half the cohorts are homogeneous (whole-blood-like), half are independent
  compositions (constructed-mixture-like).
- The v5 synthetic shift stays on top, drawn once per cohort, plus a small
  per-sample shift.
- Model `Deconvolver(cohort=True)` takes the cohort features. `--no-cohort`
  trains the v5 architecture on the same data, as the ablation.
- Validation: cohorts of 8 from held-out donors of both studies, cycling
  GSE103541 alone, GSE35069 reference -> GSE103541 mixture, and the reverse.
v2-v5 numbers were scored on a different validation set and are not comparable.

All scores here are synthetic. Real-data scoring is a separate frozen step
(EVALUATION.md).
"""

